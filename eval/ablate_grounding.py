"""Grounding-judge ablation (steps 4.4 / 4.8).

    python eval/ablate_grounding.py [--out reports/PHASE_4_GROUNDING_ABLATION.md]

Collects the claims the full pipeline emits on the dev scenarios, then asks each available
support judge to rate three sets:
* original   - the claim with its own citation (should be accepted)
* shuffled   - the same claim re-cited to a chunk from a different section (should be rejected)
* swapped    - another section's claim text under this claim's citation (should be rejected)
Judges: lexical (CPU, always run), nli (needs the optional model), llm (needs a configured LLM).
Judges that cannot run are reported as not run, never estimated.
"""

from __future__ import annotations

import argparse
import asyncio
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from eval.scenarios import load_scenarios  # noqa: E402
from src.config import get_settings  # noqa: E402
from src.llm.client import make_llm_client  # noqa: E402
from src.session.pipeline import SessionPipeline  # noqa: E402
from src.synthesis.grounding import LexicalSupportJudge, LLMSupportJudge  # noqa: E402
from src.telemetry.logger import TelemetryLogger  # noqa: E402


async def collect_claims(pipeline: SessionPipeline):
    claims = []
    for sc in load_scenarios():
        for t in sc.turns:
            out = await pipeline.handle_turn(sc.id, t.chunks)
            ledger = pipeline.store.get(sc.id).ledger
            claims += [ledger.claims[c] for c in out.ledger_diff["added"] if c in ledger.claims]
        pipeline.end_session(sc.id)
    return claims


def corrupt(claims, index, seed=0):
    rng = random.Random(seed)
    ids = sorted(index.chunks)
    shuffled, swapped = [], []
    for c in claims:
        own = {index.chunks[x].section for x in c.chunk_ids}
        other_ids = [x for x in ids if index.chunks[x].section not in own]
        shuffled.append(c.model_copy(update={"chunk_ids": [rng.choice(other_ids)]}))
        donors = [d for d in claims if not ({index.chunks[x].section for x in d.chunk_ids} & own)]
        if donors:
            swapped.append(c.model_copy(update={"text": rng.choice(donors).text}))
    return shuffled, swapped


async def acceptance(judge, claims, index) -> float:
    if not claims:
        return float("nan")
    ok = 0
    for c in claims:
        v = await judge.judge(c.text, "\n\n".join(index.chunks[x].text for x in c.chunk_ids))
        ok += v.supported
    return round(ok / len(claims), 4)


async def main_async(out: Path | None) -> int:
    s = get_settings()
    pipeline = SessionPipeline(s, telemetry=TelemetryLogger(None))
    claims = await collect_claims(pipeline)
    shuffled, swapped = corrupt(claims, pipeline.index)
    judges = [("lexical (threshold %.2f)" % s.lexical_support_threshold, LexicalSupportJudge(s.lexical_support_threshold))]
    rows = []
    for name, judge in judges:
        a, b, c = [await acceptance(judge, x, pipeline.index) for x in (claims, shuffled, swapped)]
        rows.append((name, a, round(1 - b, 4), round(1 - c, 4), "run"))
    rows.append(("nli (cross-encoder/nli-deberta-v3-small)", "", "", "", "not run: optional model not installed"))
    client = make_llm_client(s)
    if client is not None:  # pragma: no cover - needs a real LLM endpoint
        j = LLMSupportJudge(client)
        a, b, c = [await acceptance(j, x, pipeline.index) for x in (claims, shuffled, swapped)]
        rows.append(("llm judge", a, round(1 - b, 4), round(1 - c, 4), "run"))
    else:
        rows.append(("llm judge", "", "", "", "not run: no LLM configured"))

    head = ("| judge | accepts original claims | rejects shuffled citations | rejects swapped text | status |\n"
            "|---|---|---|---|---|\n")
    table = head + "\n".join(f"| {n} | {a} | {b} | {c} | {st} |" for n, a, b, c, st in rows)
    text = (
        "# Phase 4 grounding-judge ablation\n\n"
        f"Generated by `python eval/ablate_grounding.py`. {len(claims)} claims emitted by the full pipeline on the "
        f"30 dev scenarios (extractive generator, no LLM); {len(shuffled)} shuffled-citation and {len(swapped)} "
        "swapped-text corruptions of them. Higher is better in every column.\n\n" + table + "\n\n"
        "The playbook asks for NLI vs LLM-judge. Neither could run in this environment (no optional model, no "
        "LLM), so only the lexical CPU judge is measured. The claims are verbatim corpus spans, so accepting the "
        "originals is the easy case; the corruption columns show whether the judge rejects misattributed claims.\n"
    )
    print(table)
    if out:
        out.write_text(text, encoding="utf-8")
        print(f"wrote {out}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=None)
    return asyncio.run(main_async(parser.parse_args().out))


if __name__ == "__main__":
    sys.exit(main())
