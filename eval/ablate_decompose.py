"""Phase 3 ablations (step 3.7).

    python eval/ablate_decompose.py [--out reports/PHASE_3_ABLATION.md]

Required by the playbook:
* hybrid vs dense-only retrieval (BM25-only added for reference)
* with vs without the anti-fragmentation guard
Additional (cheap, same harness): speculative cache off, fusion quota off, and the
LLM decomposer (only if PRISM_LLM_PROVIDER is configured; otherwise reported as not run).
No thresholds are tuned here; every row uses the configured defaults except the one
component being ablated.
"""

from __future__ import annotations

import argparse
import asyncio
import dataclasses
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from eval.decompose_eval import build_engine, evaluate_decomposition  # noqa: E402
from eval.scenarios import load_scenarios  # noqa: E402
from src.config import get_settings  # noqa: E402
from src.llm.client import make_llm_client  # noqa: E402
from src.retrieval.factory import build_retrieval  # noqa: E402
from src.telemetry.logger import TelemetryLogger  # noqa: E402

COLS = ["config", "g3", "g3_passed", "over_split", "subq_per_compound", "intent_evidence_recall",
        "matched_recall_at_5", "retrievals_per_turn", "cache_hits", "g2"]


def row(label: str, s: dict) -> dict:
    return {
        "config": label,
        "g3": s["g3"]["rate"],
        "g3_passed": f"{s['g3']['passed']}/{s['g3']['compound_turns']}",
        "over_split": f"{s['over_split']['over_split']}/{s['over_split']['single_intent_turns']}",
        "subq_per_compound": s["subqueries_per_compound_turn"],
        "intent_evidence_recall": s["intent_evidence_recall"],
        "matched_recall_at_5": s["matched_subquery_recall_at_5"],
        "retrievals_per_turn": s["retrievals_per_eligible_turn"],
        "cache_hits": s["cache_hits"],
        "g2": s["g2_early_rate"],
    }


def fmt(rows: list[dict]) -> str:
    head = "| " + " | ".join(COLS) + " |\n|" + "---|" * len(COLS) + "\n"
    return head + "\n".join("| " + " | ".join(str(r.get(c, "")) for c in COLS) + " |" for r in rows)


async def main_async(out: Path | None) -> int:
    base = get_settings()
    scenarios = load_scenarios()
    stack = build_retrieval(base)
    quiet = TelemetryLogger(None)

    configs = [
        ("full: rules+guard, hybrid (default)", base, {}),
        ("retrieval: dense-only (hashing embedder)", base, {"retriever": "dense"}),
        ("retrieval: bm25-only (reference)", base, {"retriever": "bm25"}),
        ("anti-fragmentation guard OFF", base, {"anti_fragmentation": False}),
        ("speculative cache OFF", dataclasses.replace(base, cache_similarity=0.0), {}),
        ("fusion quota OFF", dataclasses.replace(base, fusion_quota=0), {}),
    ]
    rows, details = [], {}
    for label, settings, kw in configs:
        engine = build_engine(settings, stack=stack, telemetry=quiet, **kw)
        result = await evaluate_decomposition(scenarios, engine)
        rows.append(row(label, result["summary"]))
        details[label] = result

    llm_note = "not run: no LLM configured (PRISM_LLM_PROVIDER=none); see README teammate setup"
    if make_llm_client(base) is not None:  # pragma: no cover - needs a real LLM endpoint
        engine = build_engine(dataclasses.replace(base, decomposer="llm"), stack=stack, telemetry=quiet)
        rows.append(row("decomposer: llm", (await evaluate_decomposition(scenarios, engine))["summary"]))
        llm_note = "run with the configured LLM"
    else:
        rows.append({"config": "decomposer: llm", "g3": llm_note})

    full = details[configs[0][0]]
    off = details["anti-fragmentation guard OFF"]
    split_diff = [
        f"- `{a['scenario']} t{a['turn']}`: with guard {len(a['predicted'])} sub-quer{'y' if len(a['predicted']) == 1 else 'ies'}"
        f" -> without guard {len(b['predicted'])}: " + " || ".join(p["text"] for p in b["predicted"])
        for a, b in zip(full["turns"], off["turns"]) if len(a["predicted"]) != len(b["predicted"])
    ]
    text = (
        "# Phase 3 ablation: decomposition and fusion\n\n"
        "Generated by `python eval/ablate_decompose.py` on the 30 dev scenarios (40 turns; 12 compound turns "
        "with >= 2 gold sub-intents; 22 single-intent retrieval turns). Every row uses the default configuration "
        "except the ablated component. `g3` = share of compound turns with >= 2 correctly identified sub-intents "
        "(target 0.70); `over_split` = single-intent turns split into > 1 sub-query; `intent_evidence_recall` = "
        "share of gold sub-intents whose supporting section is in the fused evidence; `matched_recall_at_5` = "
        "the matched sub-query's own top-5 contains the gold section; `g2` = early retrieval rate of the full "
        "pipeline.\n\n"
        + fmt(rows) + "\n\n"
        f"LLM decomposer: {llm_note}.\n\n"
        "Note: the dense retriever uses the default hashing embedder, which is lexical rather than semantic; "
        "the dense-only row is not representative of a real embedding model.\n\n"
        "## Sub-query differences with vs without the anti-fragmentation guard\n\n"
        + ("\n".join(split_diff) if split_diff else "- none") + "\n"
    )
    print(fmt(rows))
    if out:
        out.write_text(text, encoding="utf-8")
        print(f"wrote {out}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=None)
    return asyncio.run(main_async(parser.parse_args().out))


if __name__ == "__main__":
    sys.exit(main())
